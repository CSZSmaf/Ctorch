#include "decoder_model.h"

#include <iostream>

int main(int argc, char** argv) {
    if (argc < 3 || argc > 5) {
        std::cout << "usage: ctorch_decoder_generate <weights.ct> <prefix> [tokens] [cpu|cuda]\n";
        return 0;
    }
    const auto device = argc > 4 && std::string_view(argv[4]) == "cuda" ? dl::Device::cuda() : dl::Device::cpu();
    const dl::Index count = argc > 3 ? std::stoll(argv[3]) : 32;
    const std::string prefix = argv[2];
    const auto length = static_cast<dl::Index>(prefix.size());
    if (length == 0 || count < 0 || length + count > examples::decoder_text.length)
        throw std::invalid_argument("a nonempty prefix and generated bytes must fit the 128-byte context");
    examples::ByteDecoder model;
    model.load_state_dict(dl::io::load(argv[1]));
    model.to(device);
    model.eval();
    auto cache = model.make_cache();
    std::vector<dl::Index> bytes;
    for (unsigned char byte : prefix) bytes.push_back(byte);
    auto input = dl::from_span<dl::Index>(bytes, {1, length}, false, device);
    std::cout << prefix;
    // 首次计算整个前缀；随后每次仅输入上一步生成的一个字节。
    for (dl::Index i = 0; i < count; ++i) {
        auto logits = model.decode(input, cache).select(1, input.size(1) - 1);
        const auto next = dl::argmax(logits, -1).item<dl::Index>();
        std::cout << static_cast<char>(next);
        input = dl::full({1, 1}, static_cast<double>(next), {.dtype = dl::DType::i64, .device = device});
    }
    std::cout << '\n';
}
